const ideaBlocks = [
  '很多人第一次接触这个话题时，会下意识地寻找一个立刻见效的答案。但真正决定结果的，往往不是某个技巧，而是是否把目标、对象和行动顺序想清楚。先回答“写给谁看、希望对方看完做什么”，内容才不会变成热闹却没有方向的堆砌。',
  '把复杂问题拆开，通常可以看到三个层次：表面现象、真实原因和可以执行的动作。只描述现象容易制造焦虑，只分析原因又容易停在道理上。更有效的表达，是让读者看见问题之后，马上知道自己今天能做的第一步。',
  '一个可持续的方法应当足够简单，能在忙碌的日常中重复。与其一次性做得很满，不如给自己设定明确边界：每次只解决一个问题，每个动作都有检查标准，每轮结束都留下记录。这样才能把偶然的灵感变成稳定的能力。',
  '执行过程中最常见的误区，是还没有获得反馈就频繁换方向。真正有价值的调整来自事实：读者在哪一段停留、哪些问题被反复提到、什么行动最容易完成。记录这些信号，再决定保留、删除或加强什么，效果会越来越清晰。',
  '判断一篇内容是否有用，不只看阅读数字，也要看它是否建立理解、减少犹豫并推动行动。哪怕只有一部分读者愿意收藏、转发或照着尝试，这篇文章就开始产生长期价值。数据是温度计，不是唯一目标。',
];

export function createDemoArticle(topic, options = {}) {
  const audience = options.audience || '希望解决实际问题的普通读者';
  const paragraphs = [];
  while (paragraphs.join('').length < 1250) {
    paragraphs.push(...ideaBlocks.map((item) => `${item}围绕“${topic}”，对${audience}来说，关键是把判断落实到真实场景，而不是停留在口号。`));
  }
  return {
    title: `${topic}：真正有效的做法，藏在这 3 个细节里`,
    digest: `从真实场景出发，拆解${topic}背后的关键判断与可执行方法。`,
    lead: `关于“${topic}”，信息很多，真正能落地的方法却不多。本文不制造焦虑，只用一套清楚的思路，帮你从理解走到行动。`,
    sections: [
      { heading: '一、先看清问题，再寻找答案', paragraphs: paragraphs.slice(0, 3) },
      { heading: '二、把方法变成可以重复的动作', paragraphs: paragraphs.slice(3, 6) },
      { heading: '三、用反馈完成下一轮优化', paragraphs: paragraphs.slice(6, 9) },
    ],
    conclusion: `回到“${topic}”本身，最重要的不是一次做到完美，而是先完成一轮真实行动，再依据结果持续修正。清楚、克制、可重复，往往比看起来复杂的方法更有力量。`,
    callToAction: '如果这套方法对你有帮助，欢迎收藏，并把你的实际问题留在评论区。',
    coverPrompt: `微信公众号横版封面，主题为“${topic}”，现代编辑插画，清晰视觉焦点，温暖克制，留出标题区域，无水印。`,
  };
}
